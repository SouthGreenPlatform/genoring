#!/bin/sh

# Automatically exit on error.
set -e

# Remove maintenance mode.
genoring online

# Remove offline file.
if test -f /opt/drupal/web/offline.html; then
  echo "Remove offline file."
  rm /opt/drupal/web/offline.html
fi

# Manage reverse proxy settings (ie. when served by a master GenoRing instance).
SETTINGS_DIR=/opt/drupal/web/sites/default
REVERSE_PROXY_SETTINGS="$SETTINGS_DIR/settings.reverse_proxy.php"
if [ -n "$GENORING_REVERSE_PROXY_ADDRESSES" ] && [ -f "$SETTINGS_DIR/settings.php" ]; then
  # Add settings include if missing.
  if ! grep -q "settings.reverse_proxy.php" "$SETTINGS_DIR/settings.php"; then
    echo "Add reverse proxy settings include."
    cat >>"$SETTINGS_DIR/settings.php" <<'EOF'

/**
 * Load reverse proxy settings managed by GenoRing, if available.
 */
if (file_exists($app_root . '/' . $site_path . '/settings.reverse_proxy.php')) {
  include $app_root . '/' . $site_path . '/settings.reverse_proxy.php';
}
EOF
  fi
  ADDRESSES=$(printf '%s' "$GENORING_REVERSE_PROXY_ADDRESSES" | tr ',' '\n' | grep -v '^$' | sed "s/.*/'&',/" | tr -d '\n')
  rm -f "$REVERSE_PROXY_SETTINGS"
  cat >"$REVERSE_PROXY_SETTINGS" <<EOF
<?php

// Generated by GenoRing each time it is started online. Any direct
// modification will be lost.
\$settings['reverse_proxy'] = TRUE;
\$settings['reverse_proxy_addresses'] = [$ADDRESSES];
EOF
  chmod 444 "$REVERSE_PROXY_SETTINGS"
elif [ -f "$REVERSE_PROXY_SETTINGS" ]; then
  echo "Remove reverse proxy settings."
  rm -f "$REVERSE_PROXY_SETTINGS"
fi
